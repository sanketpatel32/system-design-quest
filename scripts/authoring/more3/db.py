"""Build the third Databases round: topics 551-560 and 621-626 -> scripts/authored/fund-databases-more.json.

Run: python3 scripts/authoring/more3/db.py   (then: npm run audit)
"""
import json, os, sys
sys.path.insert(0, os.path.dirname(__file__))
import db_a, db_b, db_c, db_d, db_e, db_f, db_g, db_h

topics = db_a.T + db_b.T + db_c.T + db_d.T + db_e.T + db_f.T + db_g.T + db_h.T

# Steps whose relative order does not matter get alternative orders.
for t in topics:
    for q in t['questions']:
        if q['id'] == 't555-a6':
            q['alternativeOrders'] = [['s1', 's3', 's2', 's4', 's5']]

# 551 also links to the system-design inverted index lesson.
next(t for t in topics if t['id'] == 551)['seeAlso'].append(
    {'topicId': 63, 'why': 'Inverted indexes at search-engine scale, the next step after in-database full text'})

# Option-length balance: make a distractor at least as long as the answer (or shorten the answer).
LABELS = {
    ('t551-a1', 'd'): 'A block-range index on status, which suits sorted columns',
    ('t552-a1', 'c'): 'Each insert first searches the table for an existing equal UUID value',
    ('t552-a2', 'b'): 'It is generated by the database itself, so two values cannot collide',
    ('t552-a4', 'a'): 'A bigint sequence will run out of values within a few years of growth',
    ('t552-a4', 'c'): 'Anyone can probe nearby ids, and gaps reveal your invoice volume',
    ('t552-a7', 'b'): 'It more than doubles key size and compares by text collation',
    ('t552-a7', 'c'): 'Text UUIDs lose their randomness once the index has sorted them',
    ('t553-a2', 'd'): 'An index on parent_id plus one plain SELECT that starts at category 12',
    ('t553-a3', 'c'): 'Inserting a new reply under comment 9, deep in the thread',
    ('t555-a4', 'a'): 'The row with the largest valid_from value stored for product 5',
    ('t555-a4', 'b'): 'The row whose valid_from to valid_to period covers 3 March',
    ('t556-a1', 'd'): 'It depends on how recently the view was last refreshed by a job',
    ('t556-a4', 'd'): 'The totals column overflows its integer type at that write rate',
    ('t558-a3', 'b'): 'Older rows have moved to a slower storage format on disk over the year',
    ('t558-a4', 'a'): 'Scans read through the operating system cache and bypass the pool',
    ('t558-a4', 'c'): 'Scans reuse a small ring of buffers or enter the list mid-way',
    ('t559-a3', 'c'): 'Local time plus the fixed offset +01:00 for Berlin',
    ('t621-a1', 'd'): 'Disk reads, because the prepared statement caches the rows it returns',
    ('t621-a3', 'a'): 'Its statistics expired after five runs and were not rebuilt',
    ('t621-a4', 'b'): 'Add memory so the large scan plan runs from cached pages instead',
    ('t622-a2', 'a'): 'Throughput keeps doubling with batch size, so one statement is fastest',
    ('t622-a6', 'a'): 'A longer timeout on each batch so replies arrive in time',
}
used = set()
for t in topics:
    for q in t['questions']:
        for c in q.get('choices', []):
            k = (q['id'], c['id'])
            if k in LABELS:
                c['label'] = LABELS[k]; used.add(k)
assert used == set(LABELS), set(LABELS) - used

# Map order follows the catalog list for f4-databases (src/content/catalog.ts).
MAP = [559, 552, 560, 553, 555, 557, 551, 558, 625, 621, 624, 626, 622, 554, 556, 623]
for t in topics:
    t['order'] = 15 + MAP.index(t['id'])

ids = [t['id'] for t in topics]
assert len(set(ids)) == len(ids) and all(i in MAP for i in ids), ids
root = os.path.join(os.path.dirname(__file__), '..', '..', 'authored')
with open(os.path.join(root, 'fund-databases-more.json'), 'w') as f:
    json.dump(topics, f, ensure_ascii=False, indent=1); f.write('\n')
print('fund-databases-more.json', ids)
